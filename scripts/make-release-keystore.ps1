#requires -Version 5.1
<#
  Generates a release signing keystore for GamePouch and writes
  keystore.properties in the project root (gitignored).

  Usage:
    powershell -ExecutionPolicy Bypass -File scripts\make-release-keystore.ps1
    powershell -ExecutionPolicy Bypass -File scripts\make-release-keystore.ps1 -Alias gamepouch -Validity 10000
    powershell -ExecutionPolicy Bypass -File scripts\make-release-keystore.ps1 -StorePass <pwd> -KeyPass <pwd>   # CI / non-interactive

  WARNING
    The keystore produced here is a LOCAL DEVELOPMENT keystore. A keystore that
    signs store releases must be generated inside your secret manager / HSM and
    must never be committed. If you later enrol in Play App Signing or Huawei
    App Signing, upload the *upload key* only and keep the app signing key in
    the provider's custody.
#>
[CmdletBinding()]
param(
  [string]$Alias = 'gamepouch',
  [int]$Validity = 10000,
  [string]$DName = 'CN=GamePouch, OU=Mobile, O=GamePouch, L=, S=, C=CN',
  [string]$StorePass,
  [string]$KeyPass
)
$ErrorActionPreference = 'Stop'
$Root  = if ($PSScriptRoot) { (Resolve-Path (Join-Path $PSScriptRoot '..')).Path } else { (Resolve-Path (Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) '..')).Path }
$Tools = Join-Path $Root '.tools'
$jdk   = Join-Path $Tools 'jdk21'
if (-not (Test-Path (Join-Path $jdk 'bin\java.exe'))) { $jdk = Join-Path $Tools 'jdk17' }
if (-not (Test-Path (Join-Path $jdk 'bin\java.exe'))) { throw 'JDK not found under .tools; run scripts\setup-env.ps1 first' }

$keytool = Join-Path $jdk 'bin\keytool.exe'
$signing = Join-Path $Tools 'signing'
New-Item -ItemType Directory -Force $signing | Out-Null
$ks = Join-Path $signing 'gamepouch.jks'

if (-not $StorePass) {
  $StorePass = -join ((48..57 + 65..90 + 97..122) | Get-Random -Count 24 | ForEach-Object { [char]$_ })
}
if (-not $KeyPass) { $KeyPass = $StorePass }

if (Test-Path $ks) {
  Write-Host "keystore already exists: $ks (left untouched)" -ForegroundColor Yellow
}
else {
  Write-Host "generating release keystore -> $ks" -ForegroundColor Cyan
  & $keytool -genkeypair -v `
    -keystore $ks -storetype JKS `
    -keyalg RSA -keysize 2048 -validity $Validity `
    -alias $Alias -dname $DName `
    -storepass $StorePass -keypass $KeyPass
  if ($LASTEXITCODE -ne 0) { throw "keytool failed ($LASTEXITCODE)" }
}

$props = @"
# Auto-generated by scripts\make-release-keystore.ps1 — DO NOT COMMIT.
# This is a LOCAL DEVELOPMENT keystore. Sign store releases with a key held in
# your secret manager / HSM, and enrol in Play App Signing / Huawei signing.
storeFile=$($ks -replace '\\', '/')
storePassword=$StorePass
keyAlias=$Alias
keyPassword=$KeyPass
"@
Set-Content -LiteralPath (Join-Path $Root 'keystore.properties') -Value $props -Encoding ASCII

Write-Host "`nwrote keystore.properties" -ForegroundColor Green
Write-Host "  storeFile     = $ks"
Write-Host "  keyAlias      = $Alias"
Write-Host "  validity days = $Validity"
Write-Host "`n[REMINDER] backup the keystore + passwords to your secret manager NOW." -ForegroundColor Yellow
Write-Host "[REMINDER] losing it means you can never upgrade this app again." -ForegroundColor Yellow
