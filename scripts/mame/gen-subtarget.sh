#!/usr/bin/env bash
# Regenerate the GamePouch MAME subtarget from the app's multiplayer catalog.
#
# Reads app/assets/data/multiplayer.json (the "fbalpha2012" arcade section),
# resolves each driver to the MAME source file that declares it via the
# GAME()/GAMEL() macro, and writes:
#     src/mame/gamepouch.lst            (driver list, grouped by @source)
#     scripts/target/mame/gamepouch.lua (copied from scripts/mame/gamepouch.lua)
#
# Run inside WSL against a libretro/mame checkout:
#   bash /mnt/d/.../scripts/mame/gen-subtarget.sh /home/ubuntu/mame-build/mame
set -e

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
MAME_SRC=${1:-/home/ubuntu/mame-build/mame}
cd "$MAME_SRC" || exit 1

# Derive the driver list straight from the shipped catalog so the two never
# drift apart. Only the arcade (fbalpha2012) section is relevant.
python3 - "$SCRIPT_DIR/../../app/assets/data/multiplayer.json" > /tmp/drv_raw.txt <<'PY'
import json, sys, re
data = json.load(open(sys.argv[1], encoding='utf-8'))
names = [k for k in data.get('fbalpha2012', {})]
# MAME short names never contain spaces; the catalog has a few stray keys.
valid = sorted({n.strip().lower() for n in names
                if n and not re.search(r'\s', n)})
print('\n'.join(valid))
PY

# The catalog only lists games that support netplay, but a single-player arcade
# zip must launch regardless — deriving the compiled driver set from the
# multiplayer catalog alone meant every CPS1/CPS2/NeoGeo game that is *not* in
# the catalog was missing from the core and failed with "Driver not found".
#
# We therefore union the catalog with the *actual* machine names shipped in the
# user's ROM library. This is deliberately TARGETED: we add only the games the
# user owns (resolved to their MAME source file by the loop below) and NOT the
# entire capcom/snk source tree. Including every driver in those folders pulls in
# stray NeoGeo BIOS/device definitions that break the neogeo.zip BIOS lookup and
# regress the 64 already-working NeoGeo titles.
EXTRA="$SCRIPT_DIR/extra-drivers.txt"
if [ -f "$EXTRA" ]; then
  echo "=== extra drivers from user library: $(wc -l < "$EXTRA") ==="
  tr -d '\r' < "$EXTRA" >> /tmp/drv_raw.txt
fi

# Merged, de-duplicated driver list.
sort -u /tmp/drv_raw.txt -o /tmp/drv_raw.txt

# The NeoGeo system BIOS root machine 'neogeo' (and the AES home-console variant)
# is declared with the CONS() macro, so it is never pulled from the catalog by the
# GAME()/GAMEL() scan above. Without it MAME reports "missing NeoGeo system BIOS"
# for *every* NeoGeo game. Force these BIOS/motherboard machines into the build.
printf 'neogeo\naes\n' >> /tmp/drv_raw.txt
sort -u /tmp/drv_raw.txt -o /tmp/drv_raw.txt

cp "$SCRIPT_DIR/gamepouch.lua" scripts/target/mame/gamepouch.lua

OUT=src/mame/gamepouch.lst
{
  echo "// license:BSD-3-Clause"
  echo "// copyright-holders:GamePouch"
  echo "/*******************************************************************************"
  echo ""
  echo "    gamepouch.lst"
  echo ""
  echo "    Arcade drivers referenced by GamePouch's multiplayer catalog"
  echo "    (app/assets/data/multiplayer.json, \"fbalpha2012\" section)."
  echo "    Generated by scripts/mame/gen-subtarget.sh - do not edit by hand."
  echo ""
  echo "*******************************************************************************/"
  echo ""
} > "$OUT"

: > /tmp/map.txt
while read -r d; do
  [ -z "$d" ] && continue
  f=$(grep -rl --include='*.cpp' -E "(GAME|GAMEL|CONS)\([^,]*,[[:space:]]*${d}[[:space:]]*," src/mame 2>/dev/null | head -1)
  if [ -z "$f" ]; then echo "SKIP (not in this MAME): $d"; continue; fi
  echo "${f#src/mame/} $d" >> /tmp/map.txt
done < /tmp/drv_raw.txt

cut -d' ' -f1 /tmp/map.txt | sort -u | while read -r rel; do
  echo "@source:$rel" >> "$OUT"
  grep "^$rel " /tmp/map.txt | cut -d' ' -f2 >> "$OUT"
  echo "" >> "$OUT"
done

echo "=== drivers included: $(wc -l < /tmp/map.txt) ==="
echo "=== manufacturer folders ==="
cut -d/ -f1 /tmp/map.txt | sort | uniq -c | sort -rn
